export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug)
}

export function getProductsByCategory(category: string): Product[] {
  return products.filter((p) => p.category === category)
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.featured)
}

export function getRelatedProducts(currentProduct: Product, limit = 3): Product[] {
  return products
    .filter(
      (p) =>
        p.id !== currentProduct.id &&
        (p.category === currentProduct.category ||
          p.usageTypes.some((ut) => currentProduct.usageTypes.includes(ut)))
    )
    .slice(0, limit)
}

export function getVerticalTanks(): Product[] {
  return products.filter((p) => p.category === 'vertical')
}
